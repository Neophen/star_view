defmodule StarView.Template.Program do
  @moduledoc """
  A compiled `~STAR` rendering program. Compiler output; not a construction API.

  `run` is a capture-free function generated by the `~STAR` compiler from one
  template skeleton. `values` holds the already-evaluated expressions of one
  snapshot. The function owns every static byte and the template structure:

    * `run.(:render, values)` returns HTML iodata.
    * `run.(:nodes, values)` returns the equivalent `StarView.Template.Node`
      list, which may contain nested programs.
    * `run.(:key, values)` returns the item key for keyed collections, or `nil`.
    * Any other mode or a malformed `values` tuple raises `ArgumentError`.

  Rendering and materializing never evaluate template expressions again; they
  only read `values`. `values` is ordinary data and may be replaced or mutated,
  so the generated code escapes and validates it on every call exactly like a
  hand-built tree. There is no cached HTML, static data or tree in the struct.

  `run` is executable code and is trusted like a `Phoenix.HTML.Safe`
  implementation: whoever supplies it chooses the markup. Programs are
  ordinary server-side values. They are not meant to be serialized or accepted
  from untrusted transports.

  In modules, the compiler emits hidden named functions and stores external
  captures. Snapshots do not pin old module code. An unchanged program works
  after recompilation; a removed program raises `StarView.Template.StaleProgramError`.
  Diffing treats this as `:template_changed`, including nested programs.

  Moduleless evaluation and templates expanded after the compiler hook use
  local functions instead. Those values have the ordinary code-lifetime limits
  of local functions. They are intended for immediate evaluation.
  """

  alias StarView.Template
  alias StarView.Template.Node
  alias StarView.Template.Renderer

  @type t :: %__MODULE__{run: (atom(), tuple() -> term()), values: tuple()}

  @enforce_keys [:run, :values]
  defstruct [:run, :values]

  @doc false
  def render(program), do: run!(program, :render)

  @doc false
  def node_key(program), do: run!(program, :key)

  @doc "Returns the program's nodes with nested programs and templates expanded."
  @spec nodes(t()) :: [Node.t()]
  def nodes(program), do: program |> run!(:nodes) |> nodes_result!() |> expand_nodes()

  @doc false
  def template(%Template{} = template) do
    case Template.representation!(template) do
      {:nodes, nodes} -> %{template | nodes: expand_nodes(nodes)}
      {:program, program} -> %{template | nodes: nodes(program), program: nil}
    end
  end

  defp run!(%__MODULE__{run: run, values: values}, mode)
       when is_function(run, 2) and is_tuple(values), do: call(run, mode, values)

  defp run!(other, _mode),
    do: raise(ArgumentError, "invalid compiled ~STAR program: #{inspect(other)}")

  defp call(run, mode, values) do
    run.(mode, values)
  rescue
    error in UndefinedFunctionError -> callback_error(error, __STACKTRACE__, run)
  end

  defp callback_error(error, stack, run) do
    {:module, module} = :erlang.fun_info(run, :module)
    {:name, name} = :erlang.fun_info(run, :name)
    unavailable_callback(error, stack, {module, name, 2})
  end

  defp unavailable_callback(
         %UndefinedFunctionError{module: module, function: name, arity: arity},
         _stack,
         {module, name, arity}
       ), do: raise(StarView.Template.StaleProgramError)

  defp unavailable_callback(error, stack, _callback), do: reraise(error, stack)

  defp nodes_result!(nodes) when is_list(nodes), do: nodes

  defp nodes_result!(other),
    do:
      raise(
        ArgumentError,
        "compiled ~STAR program must return a node list, got: #{inspect(other)}"
      )

  # Expansion keeps unknown entries in place so the renderer and diff report
  # malformed hand-built trees with their usual errors.

  @doc false
  def expand_nodes(nodes) when is_list(nodes), do: Enum.flat_map(nodes, &expand_entry/1)
  def expand_nodes(other), do: other

  defp expand_entry(%__MODULE__{} = program), do: nodes(program)
  defp expand_entry(%Node{} = node), do: [expand_node(node)]
  defp expand_entry(other), do: [other]

  defp expand_node(%Node{kind: kind, value: value} = node) when kind in [:value, :component],
    do: expand_value_node(node, value)

  defp expand_node(%Node{children: []} = node), do: node

  defp expand_node(%Node{children: children} = node),
    do: %{node | children: expand_nodes(children)}

  defp expand_value_node(node, %Template{} = template), do: %{node | value: template(template)}

  defp expand_value_node(node, value) when is_list(value),
    do: expand_list_node(node, value, Renderer.structured_list?(value))

  defp expand_value_node(node, _value), do: node

  defp expand_list_node(node, list, true), do: %{node | value: expand_list(list)}
  defp expand_list_node(node, _list, false), do: node

  defp expand_list([head | tail]), do: [expand_value(head) | expand_list(tail)]
  defp expand_list(tail), do: tail

  defp expand_value(%Template{} = template), do: template(template)
  defp expand_value(list) when is_list(list), do: expand_list(list)
  defp expand_value(value), do: value
end
